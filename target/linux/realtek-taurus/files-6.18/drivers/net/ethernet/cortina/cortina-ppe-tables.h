/*
 * Mask table: a set bit excludes a key field. Entries 0-7 are the stock
 * masks; entry 8 keeps only the 5-tuple, so an install keyed from the flow
 * rule hashes like the parsed frame. Its 17-bit L4 port fields must be zero:
 * the top bit selects range matching, which would alias flows that differ
 * only in their ports.
 */
#define PPE_MASK_5TUPLE			8
#define PPE_MASK_L4_DP_LSB		10
#define PPE_MASK_L4_SP_LSB		27
#define PPE_MASK_L4_PORT_BITS		17
#define PPE_MASK5_W0			0x000003ffu
#define PPE_MASK5_W1			0x827ff000u
#define PPE_MASK5_W2			0xff3fd100u
#define PPE_MASK5_W3			0xffffffffu

static_assert((PPE_MASK5_W0 & GENMASK(31, PPE_MASK_L4_DP_LSB)) == 0);
static_assert((PPE_MASK5_W1 &
	       GENMASK(PPE_MASK_L4_SP_LSB + PPE_MASK_L4_PORT_BITS - 1 - 32, 0)) == 0);

