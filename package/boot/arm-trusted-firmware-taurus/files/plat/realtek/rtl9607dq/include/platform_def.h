#ifndef PLATFORM_DEF_H
#define PLATFORM_DEF_H

#include <arch.h>
#include <common/tbbr/tbbr_img_def.h>
#include <lib/utils_def.h>
#include <plat/common/common_def.h>

#define PLATFORM_LINKER_FORMAT		"elf64-littleaarch64"
#define PLATFORM_LINKER_ARCH		aarch64

#define PLATFORM_STACK_SIZE		0x1000

#define PLATFORM_MAX_CPUS_PER_CLUSTER	4
#define PLATFORM_CLUSTER_COUNT		1
#define PLATFORM_CORE_COUNT		(PLATFORM_CLUSTER_COUNT * \
					 PLATFORM_MAX_CPUS_PER_CLUSTER)

#define PLAT_PRIMARY_CPU		0x0

#define PLAT_MAX_PWR_LVL		MPIDR_AFFLVL2
#define PLAT_NUM_PWR_DOMAINS		(PLATFORM_CLUSTER_COUNT + \
					 PLATFORM_CORE_COUNT + \
					 PLATFORM_CORE_COUNT)
#define PLAT_MAX_RET_STATE		1
#define PLAT_MAX_OFF_STATE		2

/* 256 KiB secure DRAM window reserved by BL2 and Linux (tz@ffc0000) */
#define BL31_BASE			ULL(0x0ffc0000)
#define BL31_LIMIT			ULL(0x10000000)

/* Non-secure DRAM and BL33 (U-Boot) load address */
#define PLAT_TAURUS_DRAM_BASE		ULL(0x00000000)
#define PLAT_TAURUS_DRAM_SIZE		ULL(0x20000000)
#define PLAT_TAURUS_BL33_BASE		ULL(0x04000000)
#define PLAT_TAURUS_BL33_MAX_SIZE	ULL(0x00100000)

/* On-chip SRAM (BL2 resident + handoff flags) */
#define PLAT_TAURUS_SRAM_BASE		ULL(0x80000000)
#define PLAT_TAURUS_SRAM_SIZE		ULL(0x00050000)
#define PLAT_TAURUS_FIP_FLAG_ADDR	ULL(0x800474e8)

/* Peripheral MMIO windows */
#define PLAT_TAURUS_PERIPH_BASE		ULL(0xf4000000)
#define PLAT_TAURUS_PERIPH_SIZE		ULL(0x03000000)

#define TAURUS_DDR_DRR_REG		ULL(0xf4310010)
#define TAURUS_GLB_BASE			ULL(0xf4320000)
#define TAURUS_GLB_ARM_RESET		(TAURUS_GLB_BASE + 0x0a8)
#define TAURUS_GLB_GLOBAL_CONFIG	(TAURUS_GLB_BASE + 0x0c0)
#define TAURUS_GLB_ARM_CONFIG_B		(TAURUS_GLB_BASE + 0x140)
#define TAURUS_GLB_ARM_CONFIG_D0	(TAURUS_GLB_BASE + 0x14c)
#define TAURUS_RVBAR_ROM		0x3fffc000U	/* 0xffff0000 >> 2 */
#define TAURUS_GLB_SCRATCH		(TAURUS_GLB_BASE + 0x19c)
#define TAURUS_GLB_SECURITY_OVERRIDE	(TAURUS_GLB_BASE + 0x218)
#define TAURUS_GLB_TMS_REG_A		(TAURUS_GLB_BASE + 0x264)
#define TAURUS_GLB_TMS_REG_B		(TAURUS_GLB_BASE + 0x268)
#define TAURUS_GLB_TMS_REG_C		(TAURUS_GLB_BASE + 0x26c)
#define TAURUS_GLB_TMS_TEMP_DATA	(TAURUS_GLB_BASE + 0x270)

#define TAURUS_CCI_BASE			ULL(0xf6000000)
#define TAURUS_CCI_CLUSTER_SLAVE	2

#define TAURUS_QSPI_BASE		ULL(0xf4324000)
#define TAURUS_WDT_BASE			ULL(0xf432901c)
#define TAURUS_UART0_BASE		ULL(0xf43291b0)
#define TAURUS_UART0_CLK_IN_HZ		125000000
#define TAURUS_UART0_BAUDRATE		115200

/* GICv3 (40-bit AXI space) */
#define TAURUS_GIC_BASE			ULL(0x4f8000000)
#define TAURUS_GIC_SIZE			ULL(0x000200000)
#define TAURUS_GICD_BASE		ULL(0x4f8000000)
#define TAURUS_GICR_BASE		ULL(0x4f8040000)

/* FIP slots in SPI-NAND */
#define TAURUS_FIP0_OFFSET		0x040000U
#define TAURUS_FIP1_OFFSET		0x100000U

/* MMU / xlat tables */
#define PLAT_PHY_ADDR_SPACE_SIZE	(ULL(1) << 36)
#define PLAT_VIRT_ADDR_SPACE_SIZE	(ULL(1) << 36)
#define MAX_XLAT_TABLES			8
#define MAX_MMAP_REGIONS		10
#define CACHE_WRITEBACK_SHIFT		6
#define CACHE_WRITEBACK_GRANULE		(1 << CACHE_WRITEBACK_SHIFT)

#define SYS_COUNTER_FREQ_IN_TICKS	25000000

#endif /* PLATFORM_DEF_H */
